def actualizar_resultado(
    pick_id: int,
    resultado: str,
    closing_odds: float | None = None,
    db_path: str = DB_PATH,
) -> dict[str, Any] | None:
    inicializar_db(db_path)
    resultado = resultado.lower().strip()

    if resultado not in {"win", "loss", "push"}:
        raise ValueError("resultado debe ser win, loss o push")

    with conectar(db_path) as conn:
        row = conn.execute("SELECT * FROM picks WHERE id = ?", (pick_id,)).fetchone()

        if row is None:
            return None

        pick = dict(row)
        importe = float(pick["importe_sugerido"] or 0)
        cuota = float(pick["cuota"] or 0)

        if resultado == "win":
            profit_loss = round(importe * (cuota - 1), 2)
        elif resultado == "loss":
            profit_loss = round(-importe, 2)
        else:
            profit_loss = 0

        conn.execute(
            """
            UPDATE picks
            SET estado = 'cerrada',
                resultado = ?,
                closing_odds = ?,
                profit_loss = ?
            WHERE id = ?
            """,
            (resultado, closing_odds, profit_loss, pick_id),
        )
        conn.commit()

        updated = conn.execute("SELECT * FROM picks WHERE id = ?", (pick_id,)).fetchone()
    updated_dict = dict(updated)
    resolved_closing = closing_odds

    if resolved_closing is None:
        resolved_closing = obtener_closing_odds_pick(pick_id, db_path=db_path)
        if resolved_closing is not None:
            with conectar(db_path) as conn:
                conn.execute(
                    "UPDATE picks SET closing_odds = ? WHERE id = ?",
                    (resolved_closing, pick_id),
                )
                conn.commit()
                refreshed = conn.execute("SELECT * FROM picks WHERE id = ?", (pick_id,)).fetchone()
                if refreshed is not None:
                    updated_dict = dict(refreshed)

    registrar_evaluacion_pick(
        pick_id=pick_id,
        resultado=resultado,
        closing_odds=resolved_closing,
        db_path=db_path,
    )

    return updated_dict


