def _evaluar_penalizacion_historica(metricas: dict[str, Any]) -> dict[str, Any] | None:
    cerradas = int(metricas.get("cerradas") or 0)

    if cerradas < 5:
        return None

    score = 0
    razones = []
    roi = float(metricas.get("roi") or 0)
    hit_rate = float(metricas.get("hit_rate") or 0)
    clv_medio = metricas.get("clv_medio")
    clv_positivo_pct = metricas.get("clv_positivo_pct")
    clv_muestras = int(metricas.get("clv_muestras") or 0)

    if roi <= -8:
        score += 12
        razones.append("ROI muy negativo")
    elif roi < 0:
        score += 6
        razones.append("ROI negativo")

    if clv_medio is not None:
        clv_medio = float(clv_medio)
        if clv_medio <= -3:
            score += 10
            razones.append("CLV muy negativo")
        elif clv_medio < 0:
            score += 5
            razones.append("CLV negativo")

    if cerradas >= 8 and hit_rate < 45:
        score += 4
        razones.append("Hit rate flojo")

    if clv_muestras >= 4 and clv_positivo_pct is not None and float(clv_positivo_pct) < 45:
        score += 4
        razones.append("Poco CLV positivo")

    if score < 8:
        return None

    if score >= 18:
        level = "alta"
    elif score >= 12:
        level = "media"
    else:
        level = "moderada"

    return {
        "penalty_score": score,
        "level": level,
        "reasons": razones,
        "sample_closed": cerradas,
    }


def _recent_clv_streak_penalty(
    rows: list[dict[str, Any]],
    *,
    min_streak: int = 3,
) -> dict[str, Any] | None:
    negatives: list[float] = []

    for row in rows:
        clv_raw = row.get("clv_pct")
        if clv_raw is None:
            continue
        clv = float(clv_raw)
        if clv < 0:
            negatives.append(clv)
            continue
        break

    streak = len(negatives)
    if streak < min_streak:
        return None

    avg_negative = sum(negatives) / streak if negatives else 0.0
    score = 0
    reasons = []

    if streak >= 5 and avg_negative <= -2.5:
        score += 14
        reasons.append("Racha CLV muy negativa reciente")
    elif streak >= 4 and avg_negative <= -1.75:
        score += 10
        reasons.append("Racha CLV negativa reciente")
    elif streak >= 3 and avg_negative <= -1.0:
        score += 6
        reasons.append("Inicio de deriva CLV reciente")

    if score == 0:
        return None

    level = "alta" if score >= 14 else "media" if score >= 10 else "moderada"
    return {
        "penalty_score": score,
        "level": level,
        "reasons": reasons,
        "streak_size": streak,
        "streak_avg_clv": round(avg_negative, 2),
    }


