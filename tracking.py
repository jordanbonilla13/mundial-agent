def _parse_iso_datetime(value: Any) -> datetime | None:
    text = str(value or "").strip()
    if not text:
        return None
    try:
        if text.endswith("Z"):
            text = text[:-1] + "+00:00"
        dt = datetime.fromisoformat(text)
        if dt.tzinfo is None:
            return dt.replace(tzinfo=UTC)
        return dt.astimezone(UTC)
    except ValueError:
        return None


def obtener_resets_historial_deportes(db_path: str = DB_PATH) -> dict[str, str]:
    raw = obtener_setting(SPORT_HISTORY_RESETS_SETTING, "{}", db_path=db_path) or "{}"
    try:
        data = json.loads(raw)
    except json.JSONDecodeError:
        return {}

    if not isinstance(data, dict):
        return {}

    sanitized: dict[str, str] = {}
    for sport_label, cutoff in data.items():
        sport = str(sport_label or "").strip()
        cutoff_text = str(cutoff or "").strip()
        if not sport or not cutoff_text:
            continue
        if _parse_iso_datetime(cutoff_text) is None:
            continue
        sanitized[sport] = cutoff_text
    return sanitized


def guardar_reset_historial_deporte(
    sport_label: str,
    cutoff_iso: str | None = None,
    db_path: str = DB_PATH,
) -> dict[str, str]:
    sport = str(sport_label or "").strip()
    if not sport:
        raise ValueError("sport_label es obligatorio")

    cutoff_text = str(cutoff_iso or datetime.now(UTC).isoformat()).strip()
    cutoff_dt = _parse_iso_datetime(cutoff_text)
    if cutoff_dt is None:
        raise ValueError("cutoff_iso invalido")

    resets = obtener_resets_historial_deportes(db_path=db_path)
    resets[sport] = cutoff_dt.isoformat()
    guardar_setting(
        SPORT_HISTORY_RESETS_SETTING,
        json.dumps(resets, ensure_ascii=False),
        db_path=db_path,
    )
    return resets


def eliminar_reset_historial_deporte(
    sport_label: str,
    db_path: str = DB_PATH,
) -> dict[str, str]:
    sport = str(sport_label or "").strip()
    resets = obtener_resets_historial_deportes(db_path=db_path)
    if sport in resets:
        del resets[sport]
        guardar_setting(
            SPORT_HISTORY_RESETS_SETTING,
            json.dumps(resets, ensure_ascii=False),
            db_path=db_path,
        )
    return resets


def filtrar_registros_por_reset_deporte(
    rows: list[dict[str, Any]],
    *,
    db_path: str = DB_PATH,
    sport_getter: Any = None,
    created_field: str = "created_at",
) -> list[dict[str, Any]]:
    resets = obtener_resets_historial_deportes(db_path=db_path)
    if not resets:
        return list(rows)

    filtered: list[dict[str, Any]] = []
    for row in rows:
        if callable(sport_getter):
            sport = str(sport_getter(row) or "").strip()
        else:
            sport = str(row.get("sport_label") or "").strip()

        cutoff_text = resets.get(sport)
        if not cutoff_text:
            filtered.append(row)
            continue

        created_dt = _parse_iso_datetime(row.get(created_field))
        cutoff_dt = _parse_iso_datetime(cutoff_text)
        if created_dt is None or cutoff_dt is None or created_dt >= cutoff_dt:
            filtered.append(row)

    return filtered


def obtener_bankroll(default: float = 25, db_path: str = DB_PATH) -> float:
    value = obtener_setting("bankroll_actual", str(default), db_path=db_path)

    try:
        return round(float(value), 2)
    except (TypeError, ValueError):
        return round(default, 2)


def actualizar_bankroll(bankroll: float, db_path: str = DB_PATH) -> float:
    if bankroll < 0:
        raise ValueError("bankroll debe ser mayor o igual que 0")

    bankroll = round(float(bankroll), 2)
    guardar_setting("bankroll_actual", str(bankroll), db_path=db_path)
    return bankroll


def guardar_snapshot_cuotas(
    partidos: list[dict[str, Any]],
    db_path: str = DB_PATH,
) -> int:
    inicializar_db(db_path)
    ahora = datetime.now(UTC).isoformat()
    guardadas = 0

    with conectar(db_path) as conn:
        for partido in partidos:
            home = partido.get("home_team")
            away = partido.get("away_team")
            partido_nombre = f"{home} vs {away}" if home and away else None

            for bookmaker in partido.get("bookmakers", []):
                casa = bookmaker.get("title")

                for market in bookmaker.get("markets", []):
                    market_key = market.get("key")

                    for outcome in market.get("outcomes", []):
                        price = outcome.get("price")

                        if not price:
                            continue

                        conn.execute(
                            """
                            INSERT INTO odds_snapshots (
                                created_at, event_id, commence_time, sport_key, sport_label,
                                league_key, league_label, partido, bookmaker,
                                market_key, outcome_name, outcome_point, price, raw_json
                            )
                            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                            """,
                            (
                                ahora,
                                partido.get("id"),
                                partido.get("commence_time"),
                                partido.get("sport_key"),
                                partido.get("sport_label"),
                                partido.get("league_key"),
                                partido.get("league_label"),
                                partido_nombre,
                                casa,
                                market_key,
                                outcome.get("name"),
                                outcome.get("point"),
                                float(price),
                                json.dumps({
                                    "event_id": partido.get("id"),
                                    "commence_time": partido.get("commence_time"),
                                    "sport_key": partido.get("sport_key"),
                                    "sport_label": partido.get("sport_label"),
                                    "league_key": partido.get("league_key"),
                                    "league_label": partido.get("league_label"),
                                    "partido": partido_nombre,
                                    "bookmaker": casa,
                                    "market": market_key,
                                    "outcome": outcome,
                                }, ensure_ascii=False),
                            ),
                        )
                        guardadas += 1

        conn.commit()

    return guardadas


